// Готовые квизы, которые появляются в библиотеке при первом запуске.

const q = (text, answers, correct, extra = {}) => ({
  type: 'quiz',
  text,
  time: 20,
  points: 1,
  image: '',
  answers: answers.map((a, i) => ({ text: a, correct: Array.isArray(correct) ? correct.includes(i) : i === correct })),
  ...extra
});

const tf = (text, isTrue, extra = {}) => ({
  type: 'truefalse',
  text,
  time: 10,
  points: 1,
  image: '',
  answers: [{ text: 'Верно', correct: isTrue }, { text: 'Неверно', correct: !isTrue }],
  ...extra
});

const poll = (text, answers, extra = {}) => ({
  type: 'poll',
  text,
  time: 15,
  points: 0,
  image: '',
  answers: answers.map(a => ({ text: a, correct: false })),
  ...extra
});

